CREATE TABLE IF NOT EXISTS samples (
    id                 INTEGER PRIMARY KEY,
    file_path          TEXT UNIQUE NOT NULL,
    file_name          TEXT,
    bpm                REAL,
    bpm_confidence     REAL,
    tempo_free         INTEGER DEFAULT 0,
    key_root           TEXT,
    key_mode           TEXT,
    key_agnostic       INTEGER DEFAULT 0,
    key_confidence     REAL,
    spectral_centroid  REAL,
    transient_strength REAL,
    attack_ms          REAL,
    decay_ms           REAL,
    is_loop            INTEGER DEFAULT 0,
    duration_ms        REAL,
    rms                REAL,
    mfcc               TEXT,
    inferred_role      TEXT,
    user_role          TEXT,
    genre_affinity     TEXT DEFAULT '{}',
    times_used         INTEGER DEFAULT 0,
    last_used_at       TEXT,
    added_at           TEXT,
    analysis_version   INTEGER DEFAULT 1
);
